def validate_courses(data: list[dict]) -> list[dict]:
    if not isinstance(data, list) or not data:
        raise ValueError("Course catalogue must contain a non-empty list.")

    required = {"code", "name", "credits", "level"}
    for course in data:
        if not isinstance(course, dict) or not required.issubset(course):
            raise ValueError(f"Invalid course record: {course}")

    return data


def load_courses(path: Path | None = None) -> list[dict]:
    """
    Load a course catalogue from a user-supplied JSON file when provided.
    Otherwise use the built-in catalogue derived from the uploaded transcript.
    """
    if path is None:
        return validate_courses([dict(course) for course in COURSE_CATALOGUE])

    if not path.exists():
        raise FileNotFoundError(
            f"Course catalogue not found: {path}\n"
            "Either provide an existing JSON file with --courses or omit "
            "--courses to use the built-in catalogue."
        )

    data = json.loads(path.read_text(encoding="utf-8"))
    return validate_courses(data)


def build_students(count: int) -> list[dict]:
    return [
        {
            "student_id": f"STD{i:03d}",
            "name": f"Test Student {i:03d}",
            "program": "B.Sc. Honours in Computer Science",
            "year": 4,
            "active": True,
        }
        for i in range(1, count + 1)
    ]


def choose_courses(courses: list[dict]) -> list[dict]:
    # A representative set from the 3000/4000-level Computer Science
    # curriculum is used for transcript Q&A. The full catalogue remains
    # available in courses.json for future experiments.
    selected = [c for c in courses if c["level"] in (3000, 4000)]
    return selected[:12]


