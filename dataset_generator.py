def build_metadata_records(documents: list[dict]) -> list[dict]:
    records = []
    for document in documents:
        approved = [
            v["version"]
            for v in document["version_plan"]
            if v["approval_status"] == "APPROVED"
        ]
        latest = max(v["version"] for v in document["version_plan"])
        latest_approved = max(approved) if approved else None

        records.append({
            "document_id": document["document_id"],
            "student_id": document["student_id"],
            "document_type": document["document_type"],
            "repository": document["repository"],
            "latest_version": latest,
            "latest_approved_version": latest_approved,
            "latest_approved_cid": (
                f"bafy-phase5-{document['document_id'].lower()}-v{latest_approved}"
                if latest_approved is not None else None
            ),
            "keywords": REPOSITORIES[document["repository"]]["keywords"],
        })
    return records


def build_questions(documents: list[dict]) -> list[dict]:
    questions = []
    for document in documents:
        if document["repository"] != "academic":
            continue

        courses = document["content"]["courses"]
        first, second = courses[0], courses[1]
        sid = document["student_id"]

        questions.extend([
            {
                "id": f"Q-{sid}-001",
                "category": "direct_retrieval",
                "student_id": sid,
                "document_id": document["document_id"],
                "question": f"Retrieve document {document['document_id']}.",
                "expected": "document_retrieved",
            },
            {
                "id": f"Q-{sid}-002",
                "category": "course_specific",
                "student_id": sid,
                "document_id": document["document_id"],
                "question": f"What grade did I get for {first['code']}?",
                "expected": first["grade"],
            },
            {
                "id": f"Q-{sid}-003",
                "category": "multi_course",
                "student_id": sid,
                "document_id": document["document_id"],
                "question": (
                    f"What grades did I receive for {first['code']} and "
                    f"{second['code']}?"
                ),
                "expected": {
                    first["code"]: first["grade"],
                    second["code"]: second["grade"],
                },
            },
            {
                "id": f"Q-{sid}-004",
                "category": "missing_information",
                "student_id": sid,
                "document_id": document["document_id"],
                "question": "What grade did I get for CSC9999?",
                "expected": "not_present",
            },
            {
                "id": f"Q-{sid}-005",
                "category": "unsupported_information",
                "student_id": sid,
                "document_id": document["document_id"],
                "question": "What was my attendance percentage?",
                "expected": "not_determinable",
            },
        ])
    return questions


