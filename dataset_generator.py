def generate(count: int, output: Path, courses_path: Path | None = None) -> None:
    output.mkdir(parents=True, exist_ok=True)

    courses = load_courses(courses_path)
    students = build_students(count)
    documents = build_documents(students, courses)
    metadata = build_metadata_records(documents)
    questions = build_questions(documents)
    attacks = build_security_attacks()

    manifest = {
        "dataset_name": "Hybrid-BC-AI UDocMgmt Phase 5 Evaluation Dataset",
        "dataset_version": "1.0",
        "synthetic": True,
        "students": len(students),
        "logical_documents": len(documents),
        "blockchain_version_records": sum(
            len(d["version_plan"]) for d in documents
        ),
        "repositories": list(REPOSITORIES),
        "questions": len(questions),
        "security_attacks": len(attacks),
        "integration_note": (
            "Existing TX-98765 is intentionally not modified. Phase 5 uses "
            "synthetic IDs such as TX-STD001-001."
        ),
    }

    data = {
        "students.json": students,
        "courses.json": courses,
        "documents.json": documents,
        "metadata_records.json": metadata,
        "questions.json": questions,
        "security_attacks.json": attacks,
        "manifest.json": manifest,
    }

    for filename, value in data.items():
        (output / filename).write_text(
            json.dumps(value, indent=2, ensure_ascii=False),
            encoding="utf-8",
        )

    print("Phase 5 dataset generated successfully.")
    print(f"Output: {output}")
    print(f"Students: {len(students)}")
    print(f"Logical documents: {len(documents)}")
    print(f"Blockchain versions: {manifest['blockchain_version_records']}")
    print(f"Questions: {len(questions)}")
    print(f"Security attacks: {len(attacks)}")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--students", type=int, default=20)
    parser.add_argument("--output", type=Path, default=Path("phase5_dataset"))
    parser.add_argument(
        "--courses",
        type=Path,
        default=None,
        help=(
            "Optional path to a custom courses.json file. "
            "If omitted, the built-in catalogue is used."
        ),
    )
    args = parser.parse_args()

    if args.students < 1:
        raise SystemExit("--students must be at least 1.")

    generate(args.students, args.output, args.courses)


if __name__ == "__main__":
    main()
