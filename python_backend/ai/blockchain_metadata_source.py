"""Read-only metadata adapter for the deployed UniversityRegistry contract.

The current Solidity contract can enumerate students, but it cannot enumerate
logical documents created by createDocumentVersion(): documents is a mapping
without an ID list, and DocumentVersionCreated indexes dynamic strings whose
event topics contain hashes rather than recoverable strings.

This adapter therefore exports only metadata that can actually be enumerated
from the deployed contract: student registration records. It does not infer
semester/course metadata, decrypt IPFS payloads, or claim legacy records are
approved. Explicit document-version metadata can be supplied through a
METADATA_REGISTRY_PATH snapshot generated by an independently maintained indexer.
"""
from __future__ import annotations

import os
from pathlib import Path
from typing import Any, Dict, List

from web3 import HTTPProvider, Web3

try:
    from dotenv import load_dotenv  # type: ignore
    load_dotenv(Path(__file__).resolve().parents[2] / ".env")
except Exception:
    # Environment variables may be injected by the process manager instead.
    pass

READ_ABI = [
    {
        "inputs": [],
        "name": "studentCount",
        "outputs": [{"internalType": "uint256", "name": "", "type": "uint256"}],
        "stateMutability": "view",
        "type": "function",
    },
    {
        "inputs": [{"internalType": "uint256", "name": "", "type": "uint256"}],
        "name": "studentIds",
        "outputs": [{"internalType": "string", "name": "", "type": "string"}],
        "stateMutability": "view",
        "type": "function",
    },
    {
        "inputs": [{"internalType": "string", "name": "", "type": "string"}],
        "name": "students",
        "outputs": [
            {"internalType": "string", "name": "studentId", "type": "string"},
            {"internalType": "string", "name": "name", "type": "string"},
            {"internalType": "string", "name": "program", "type": "string"},
            {"internalType": "uint8", "name": "year", "type": "uint8"},
            {"internalType": "string", "name": "documentsIPFSHash", "type": "string"},
            {"internalType": "bytes32", "name": "contentHash", "type": "bytes32"},
            {"internalType": "uint256", "name": "timestamp", "type": "uint256"},
            {"internalType": "bool", "name": "isActive", "type": "bool"},
            {"internalType": "address", "name": "studentWallet", "type": "address"},
        ],
        "stateMutability": "view",
        "type": "function",
    },
]


def load_blockchain_metadata_records() -> List[Dict[str, Any]]:
    """Read enumeratable registration metadata using an RPC connection only."""
    rpc_url = os.getenv("WEB3_PROVIDER", "").strip()
    contract_address = os.getenv("CONTRACT_ADDRESS", "").strip()
    if not rpc_url or not contract_address:
        raise RuntimeError(
            "Blockchain metadata source selected, but WEB3_PROVIDER and/or "
            "CONTRACT_ADDRESS is missing. Configure .env or set "
            "METADATA_SOURCE=json with METADATA_REGISTRY_PATH."
        )

    w3 = Web3(HTTPProvider(rpc_url, request_kwargs={"timeout": 30}))
    if not w3.is_connected():
        raise RuntimeError("Could not connect to WEB3_PROVIDER.")

    address = Web3.to_checksum_address(contract_address)
    contract = w3.eth.contract(address=address, abi=READ_ABI)

    try:
        count = int(contract.functions.studentCount().call())
    except Exception as exc:
        raise RuntimeError(
            f"Could not enumerate students from UniversityRegistry: {exc}"
        ) from exc

    records: List[Dict[str, Any]] = []
    for index in range(count):
        try:
            student_id = str(contract.functions.studentIds(index).call()).strip()
            student = contract.functions.students(student_id).call()
        except Exception as exc:
            raise RuntimeError(
                f"Could not read student metadata at index {index}: {exc}"
            ) from exc

        # Struct getter order is defined by UniversityRegistry.StudentRecord.
        if isinstance(student, dict):
            sid = str(student.get("studentId", student_id)).strip()
            cid = str(student.get("documentsIPFSHash", "") or "").strip()
            active = bool(student.get("isActive", True))
        else:
            sid = str(student[0]).strip() if len(student) > 0 else student_id
            cid = str(student[4] or "").strip() if len(student) > 4 else ""
            active = bool(student[7]) if len(student) > 7 else True

        if not sid or not active or not cid:
            continue

        records.append({
            "document_id": f"STUDENT-{sid}-REGISTRATION",
            "student_id": sid,
            "document_type": "Student Registration Record",
            "semester": None,
            "course_codes": [],
            "keywords": ["student", "registration", "enrollment", "registrar"],
            "repository": "registrar",
            "latest_version": 1,
            # Legacy registerStudent records have no approval field. Do not
            # misrepresent their CID as an approved document version.
            "latest_approved_cid": "",
            "latest_cid": cid,
            "metadata_origin": "blockchain_student_registry",
            "approval_status": "NOT_TRACKED",
        })

    return records
